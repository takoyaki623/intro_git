/** 技タイプ × 防御側タイプ配列 → 倍率（0 / .25 / .5 / 1 / 2 / 4） */
export function effectiveness(moveType, defTypes) {
  const row = CHART[moveType];
  if (!row) return 1;
  let m = 1;
  for (const t of defTypes) m *= row[t] ?? 1;
  return m;
}

/** 相性のメッセージ。等倍のときは何も出さない。 */
export function effectivenessMessage(eff, name) {
  if (eff === 0) return `${name}には こうかが ないようだ…`;
  if (eff > 1) return 'こうかは ばつぐんだ！';
  if (eff < 1) return 'こうかは いまひとつの ようだ…';
  return null;
}
